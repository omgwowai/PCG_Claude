# pypcg_s09_seed_study.py -- the generator of Tools/pypcg/data/s09_seed_study.json (the stage 9 rows of
# docs/pypcg-v2-thresholds.md). Read-only on the level; needs a V2 run of stage 9 on disk.
#   {"start": a, "count": n}   replay pypcg/stages/s09_lots on the inputs and demo parameters recorded in
#                              Saved/Reports/v2/s09/slim_42.run.json, with the editor's booleans, for
#                              seeds a .. a+n-1; merge pypcg.v2.summarize (contract tags) into
#                              Saved/Reports/v2/s09/seed_study_raw.json. Keep n <= 7 per call: about
#                              5 s per seed, and a call over ~40 s outlasts the bridge's keepalive.
#   {"distill": true, "official_seeds": {...}}
#                              write the committed study: per tag and metric the per-seed values, the
#                              official value's percentile, the median-of-5 |rel| distribution (4000
#                              draws, random.Random(0)) and the smallest 0.05-step limit that passes
#                              99 % of them; `official_seeds` (PlazaReservationSeed -> {tag: [n, m2]},
#                              measured on the official graph) is stored as given.
RUN = os.path.join(_REPO, "Saved", "Reports", "v2", "s09", "slim_42.run.json")
RAW = os.path.join(_REPO, "Saved", "Reports", "v2", "s09", "seed_study_raw.json")
OFFICIAL = os.path.join(_REPO, "Saved", "Reports", "v2", "s09", "official.json")
OUT = os.path.join(_REPO, "Tools", "pypcg", "data", "s09_seed_study.json")
LIMITS = (0.10, 0.15, 0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.75, 0.80)


def run_seeds(args):
    from pypcg import geo, stage_api, v2
    from pypcg.stages import s09_lots as S
    from pypcg.ue.ops import Ops
    rec = json.load(open(RUN, encoding="utf-8"))
    inputs = {pin: [(geo.from_json(v), frozenset(t)) for v, t in items] for pin, items in rec["inputs"].items()}
    doc = json.load(open(RAW, encoding="utf-8")) if os.path.exists(RAW) else {"runs": {}}
    ops, tags = Ops(), set(S.TAGS.values())
    t0 = time.perf_counter()
    for seed in range(int(args["start"]), int(args["start"]) + int(args["count"])):
        out, _ = stage_api.execute(S, inputs, dict(rec["params"], Seed=seed), ops)
        items = [v2.describe(v, t) for _pin, its in out.items() for v, t in its]
        doc["runs"][str(seed)] = v2.summarize(items, tags)
    with open(RAW, "w", encoding="utf-8") as fh:
        json.dump(doc, fh)
    return {"runs": len(doc["runs"]), "seconds": round(time.perf_counter() - t0, 1)}


def distill(args):
    from pypcg import v2
    from pypcg.stages import s09_lots as S
    runs = json.load(open(RAW, encoding="utf-8"))["runs"]
    tags = set(S.TAGS.values())
    so = v2.summarize(json.load(open(OFFICIAL, encoding="utf-8"))["items"], tags)
    seeds = sorted(runs, key=int)
    rng = random.Random(0)
    out = {"_": "Generated by Content/Python/pypcg_s09_seed_study.py (see its header): the stage-9 seed "
                "study behind the stage 9 rows of docs/pypcg-v2-thresholds.md.",
           "stage": 9, "seeds": [int(s) for s in seeds],
           "official_record": "Saved/Reports/v2/s09/official.json (2026-10-19, component seed 42, PlazaReservationSeed 0)",
           "official_seeds": args.get("official_seeds", {}), "tags": {}}
    for t in sorted(tags):
        o = so[t]
        row = {"official": {"n": o["n"], "area_m2": round(o["area_m2"], 2)}}
        for m, key in (("count", "n"), ("area", "area_m2")):
            vals = [runs[s].get(t, {}).get(key, 0) for s in seeds]
            rel = [(v - o[key]) / o[key] for v in vals]
            meds = sorted(abs(statistics.median(rng.sample(rel, 5))) for _ in range(4000))
            p99 = meds[int(0.99 * len(meds))]
            row[m] = {"per_seed": [round(v, 2) for v in vals], "min": round(min(vals), 2),
                      "median": round(statistics.median(vals), 2), "max": round(max(vals), 2),
                      "official_percentile": round(sum(1 for v in vals if v < o[key]) / len(vals), 3),
                      "median_of_5_abs_rel_p99": round(p99, 4),
                      "pass_rate": {str(L): round(sum(1 for x in meds if x <= L) / len(meds), 3) for L in LIMITS},
                      "limit_for_99pct": round(max(v2.DEFAULTS[m], -(-round(p99 * 1e6) // 50000) * 0.05), 2)}
        ob, worst = o["bbox"], 0.0
        for s in seeds:
            b = runs[s].get(t, {}).get("bbox")
            if b:
                worst = max(worst, ob[0][0] - b[0][0], ob[0][1] - b[0][1], b[1][0] - ob[1][0], b[1][1] - ob[1][1])
        row["bbox_worst_overshoot_m"] = round(worst / 100, 1)
        out["tags"][t] = row
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1, ensure_ascii=False)
    return {t: [r["count"]["limit_for_99pct"], r["area"]["limit_for_99pct"], r["bbox_worst_overshoot_m"]]
            for t, r in out["tags"].items()}


