def look_tables():
    src = open(os.path.join(ROOT, "Content", "Python", "cs_clear_sky.py"), encoding="utf-8").read()

    def literal(name):
        i = src.index(name + " = {")
        depth, j = 0, src.index("{", i)
        for k in range(j, len(src)):
            depth += {"{": 1, "}": -1}.get(src[k], 0)
            if depth == 0:
                body = src[j:k + 1]
                break
        body = re.sub(r"#[^\n]*", "", body).replace("CLOUD_MI", '"/Game/CitySampleSky/MI_CS_CumulusCloud_Clear"')
        return ast.literal_eval(body)
    return literal("LOOK"), literal("CVARS")


