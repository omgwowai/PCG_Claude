    import report_page2 as p2
    F = figures()
    P = passes()
    LOOK, CVARS = look_tables()
    orig = jload(os.path.join(REP, "original_state.json"))
    tree = jload(os.path.join(RDC, "tree.json"))
    renders = sorted(x["eid"] for x in tree["actions"] if x["name"] == "RenderGraphExecute - /ViewFamilies")
    first_eid = renders[0]
    first_end = min(x["eid"] for x in tree["actions"] if x["name"].startswith("RenderGraphExecute - Slate"))
    second_eid = min([e for e in renders if e > first_end] or [0])
    H = []
    a = H.append
    p1.head(a, F, CSS, first_eid, first_end, len(tree["actions"]))
    p1.look(a, F)
    p1.settings(a, F, LOOK, CVARS, orig["components"], orig["cvars"])
    p2.frame(a, F, P, first_eid, first_end, second_eid)
    p2.section_passes(a, F, P)
    p2.section_ms(a)
    p2.section_gpu(a)
    p2.section_repro(a)
    import report_page3 as p3
    st = p3.build_sections(a)
    print("section 8/9 stats", st)
    a("</main></body></html>")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(H))
    return out_path


