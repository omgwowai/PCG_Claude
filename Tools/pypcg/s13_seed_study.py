"""The distiller of Tools/pypcg/data/s13_seed_study.json -- the evidence behind the stage 13 rows of
docs/pypcg-v2-thresholds.md. Offline (system Python); run from the repo root:

    C:/Python314/python.exe Tools/pypcg/s13_seed_study.py

Stage 13 publishes one thing: the plaza-side reserved lots its second draw did not keep (`Reroute_4`, no tag;
V2 groups them as "(all)"). Which lots those are depends on the first two draws only (`Subgraph_10`, ratio
`Ratio_Plaza_vs_Trees`, and `Subgraph_0`, 0.3), so the port's distribution is `s13_leftover_lots.split` on the
recorded inputs of `Saved/Reports/v2/s13/slim_42.run.json` for seeds 1..SEEDS (no booleans, no terrain: the
published lots are reserved lots passed through). The official side is the V2 official record plus the
official graph regenerated at other COMPONENT seeds (`Content/Python/pypcg_s13_seed_study.py`, read into
`Saved/Reports/v2/s13/offseed_<k>.json`), which moves every official draw.

For count and area: the per-seed values, the official value's percentile among them, the median-of-5 |rel|
distribution against the official record (4000 draws, random.Random(0)) and the smallest 0.05-step limit that
passes 99 % of it -- the same method as stage 9's study."""
import glob
import json
import os
import random
import statistics
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "Content", "Python"))

from pypcg import geo, stage_api, v2  # noqa: E402
from pypcg.stages import s13_leftover_lots as S  # noqa: E402

D = os.path.join(REPO, "Saved", "Reports", "v2", "s13")
OUT = os.path.join(REPO, "Tools", "pypcg", "data", "s13_seed_study.json")
SEEDS = 199
LIMITS = (0.10, 0.15, 0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.75, 0.80, 0.90, 1.00)


def _all(rec):
    s = v2.summarize(rec["items"], set()).get("(all)", {"n": 0, "area_m2": 0.0})
    return s["n"], s["area_m2"]


def main():
    rec = json.load(open(os.path.join(D, "slim_42.run.json"), encoding="utf-8"))
    inputs = {}
    for pin, items in rec["inputs"].items():
        vals = []
        for v, t in items:
            try:
                vals.append((geo.from_json(v), frozenset(t)))
            except ValueError:
                pass
        inputs[pin] = vals
    params = {k: v for k, v in rec["params"].items() if k != stage_api.SEED}
    src = S.read(inputs)
    runs = {}
    for seed in range(1, SEEDS + 1):
        _kept, published, _trees = S.split(src, params, S.Draws(stage_api.Ctx(S.STAGE, seed, None).rng))
        pts = [q for p in published for q in p.outer]
        box = [[min(q[0] for q in pts), min(q[1] for q in pts)], [max(q[0] for q in pts), max(q[1] for q in pts)]]             if pts else None
        runs[seed] = (len(published), sum(geo.area_m2(p) for p in published), box)
    official = json.load(open(os.path.join(D, "official.json"), encoding="utf-8"))
    on, oa = _all(official)
    off_seeds = {"42": [on, round(oa, 2), official["instances"]["total"]]}
    for path in sorted(glob.glob(os.path.join(D, "offseed_*.json"))):
        r = json.load(open(path, encoding="utf-8"))
        n, a = _all(r)
        off_seeds[os.path.basename(path)[len("offseed_"):-5]] = [n, round(a, 2), r["instances"]["total"]]
    rng = random.Random(0)
    out = {"_": "Generated by Tools/pypcg/s13_seed_study.py (see its docstring): the stage-13 seed study behind "
                "the stage 13 rows of docs/pypcg-v2-thresholds.md.",
           "stage": 13, "seeds": [1, SEEDS], "reserved_lots": len(src["reserved"]),
           "official_record": "Saved/Reports/v2/s13/official.json (component seed 42)",
           "official_seeds": {"_": "component seed -> [published lots, their m2, instances] on the OFFICIAL graph",
                              **off_seeds},
           "official": {"n": on, "area_m2": round(oa, 2)}, "metrics": {}}
    for m, k, o in (("count", 0, on), ("area", 1, oa)):
        vals = [runs[s][k] for s in sorted(runs)]
        rel = [(x - o) / o for x in vals]
        meds = sorted(abs(statistics.median(rng.sample(rel, 5))) for _ in range(4000))
        p99 = meds[int(0.99 * len(meds))]
        offv = [v[k] for key, v in off_seeds.items() if key != "_"]
        out["metrics"][m] = {
            "per_seed": [round(x, 2) for x in vals], "min": round(min(vals), 2),
            "median": round(statistics.median(vals), 2), "max": round(max(vals), 2),
            "official_percentile": round(sum(1 for x in vals if x < o) / len(vals), 3),
            "official_seeds_range": [round(min(offv), 2), round(max(offv), 2)],
            "median_of_5_abs_rel_p99": round(p99, 4),
            "pass_rate": {str(L): round(sum(1 for x in meds if x <= L) / len(meds), 3) for L in LIMITS},
            "limit_for_99pct": round(max(v2.DEFAULTS[m], -(-round(p99 * 1e6) // 50000) * 0.05), 2)}
    ob = v2.summarize(official["items"], set())["(all)"]["bbox"]
    over = []
    for seed in sorted(runs):
        b = runs[seed][2]
        if b:
            over.append(max(ob[0][0] - b[0][0], ob[0][1] - b[0][1], b[1][0] - ob[1][0], b[1][1] - ob[1][1], 0.0))
    over.sort()
    out["bbox"] = {"official_m": [[round(v / 100, 1) for v in c] for c in ob],
                   "overshoot_m": {"median": round(statistics.median(over) / 100, 1),
                                   "p99": round(over[int(0.99 * len(over))] / 100, 1), "max": round(over[-1] / 100, 1)},
                   "reserved_lots_m": [[round(min(q[a] for p in src["reserved"] for q in p.outer) / 100, 1) for a in (0, 1)],
                                       [round(max(q[a] for p in src["reserved"] for q in p.outer) / 100, 1) for a in (0, 1)]]}
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1, ensure_ascii=False)
    res = {m: [r["limit_for_99pct"], r["official_percentile"], r["official_seeds_range"]] for m, r in out["metrics"].items()}
    res["bbox"] = out["bbox"]
    return res


if __name__ == "__main__":
    print(json.dumps(main(), indent=1))
