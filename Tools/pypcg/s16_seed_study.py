"""The stage-16 seed study behind its row in `docs/pypcg-v2-thresholds.md`: `Tools/pypcg/data/s16_seed_study.json`.

Inputs (Saved/Reports/v2/s16/, written by `pypcg_compare_stage.py` reads, 2026-10-20):
  official.json               the official graph at component seed 42 (V2's reference)
  offseed_<k>.json            the official graph at component seed k = 1, 7, 100, 1000 (the untracked editor
                              probe `Content/Python/pyg_probe_t22f_offseed.py`, then V2's read; restored after)
  slim_<s>.json / .run.json   the five V2 slim runs
and the official split's areas from `Tools/pypcg/data/s16_fixture.json`.

The total is the grass and the grass is the per-area split (`Filter_5_Areas`: one Bernoulli per forest area,
17 areas): grass = a + b x the selected (dense) m2, fitted on the six runs whose split is known (the official
seed-42 run and the five slim runs). The model's distribution over the split draws gives the probabilities the
row is sized from; the five official component seeds are where the official graph itself lands in it.
Run: `C:/Python314/python.exe Tools/pypcg/s16_seed_study.py`.
"""
import json
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path[:0] = [os.path.join(REPO, "Content", "Python")]

from pypcg import geo  # noqa: E402

D = os.path.join(REPO, "Saved", "Reports", "v2", "s16")
OFFICIAL_SEEDS = (1, 7, 100, 1000)
SLIM_SEEDS = (7, 13, 101, 977, 42)
LIMITS = (0.25, 0.30, 0.35, 0.40)
DRAWS = 200000
MEDIAN_TRIALS = 100000


def _per_mesh(name):
    return json.load(open(os.path.join(D, name + ".json"), encoding="utf-8"))["instances"]["per_mesh"]


def _grass(pm):
    return sum(v for k, v in pm.items() if "Wild_Grass" in k)


def main():
    fx = json.load(open(os.path.join(HERE, "data", "s16_fixture.json"), encoding="utf-8"))
    ref = _per_mesh("official")
    R = sum(ref.values())
    official = {"42": {"total": R, "per_mesh": ref}}
    for k in OFFICIAL_SEEDS:
        pm = _per_mesh("offseed_%d" % k)
        official[str(k)] = {"total": sum(pm.values()), "per_mesh": pm}
    rows = [{"run": "official 42", "selected_m2": round(sum(fx["split"]["selected_m2"]), 3), "grass": _grass(ref)}]
    slim = {}
    for s in SLIM_SEEDS:
        rec = json.load(open(os.path.join(D, "slim_%d.run.json" % s), encoding="utf-8"))
        sel = sum(geo.area_m2(geo.from_json(v)) for v, _t in rec["outputs"]["Selected"])
        pm = _per_mesh("slim_%d" % s)
        slim[str(s)] = {"total": sum(pm.values()), "grass": _grass(pm), "selected_m2": round(sel, 3)}
        rows.append({"run": "slim %d" % s, "selected_m2": round(sel, 3), "grass": _grass(pm)})
    n = len(rows)
    mx = sum(r["selected_m2"] for r in rows) / n
    my = sum(r["grass"] for r in rows) / n
    b = sum((r["selected_m2"] - mx) * (r["grass"] - my) for r in rows) / sum((r["selected_m2"] - mx) ** 2 for r in rows)
    a = my - b * mx
    rest = R - _grass(ref)                                  # trees + everything else, on the reference
    rng = random.Random(16)
    areas = fx["forest_areas_m2"]
    T = sorted(a + b * sum(x for x in areas if rng.random() < 0.5) + rest for _ in range(DRAWS))

    def q(f):
        return round(T[min(len(T) - 1, int(f * len(T)))])
    probs = {}
    for L in LIMITS:
        bad = sum(1 for _ in range(MEDIAN_TRIALS)
                  if abs(sorted(rng.choice(T) for _ in range(5))[2] / R - 1.0) > L)
        probs["%.2f" % L] = {"median_of_5_outside": bad / MEDIAN_TRIALS,
                             "single_run_outside": sum(1 for t in T if abs(t / R - 1.0) > L) / len(T)}
    out = {
        "_": "Generated by Tools/pypcg/s16_seed_study.py (see its docstring): the stage-16 seed study behind the "
             "stage-16 row of docs/pypcg-v2-thresholds.md.",
        "stage": 16,
        "reference": {"component_seed": 42, "total": R},
        "official_seeds": {k: {"total": v["total"], "vs_reference": round(v["total"] / R - 1.0, 4),
                               "percentile_in_model": round(sum(1 for t in T if t < v["total"]) / len(T), 3),
                               "per_mesh": v["per_mesh"]} for k, v in official.items()},
        "slim_seeds": {k: dict(v, vs_reference=round(v["total"] / R - 1.0, 4)) for k, v in slim.items()},
        "model": {"grass": "a + b x selected_m2", "a": round(a, 1), "b": round(b, 5),
                  "max_residual": round(max(abs(r["grass"] - (a + b * r["selected_m2"])) for r in rows), 1),
                  "fit_rows": rows, "forest_areas_m2": areas,
                  "total_percentiles": {"p0.5": q(0.005), "p5": q(0.05), "p50": q(0.5), "p95": q(0.95),
                                        "p99.5": q(0.995)}},
        "limits": probs,
    }
    path = os.path.join(HERE, "data", "s16_seed_study.json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=1)
    print(json.dumps({k: v for k, v in out.items() if k not in ("official_seeds", "model")}, indent=1))
    print({k: (v["total"], v["vs_reference"], v["percentile_in_model"]) for k, v in out["official_seeds"].items()})
    print(out["model"]["a"], out["model"]["b"], out["model"]["max_residual"], out["model"]["total_percentiles"])


if __name__ == "__main__":
    main()
